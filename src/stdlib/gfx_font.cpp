Rows accent_rows(const Accent accent) {
  switch (accent) {
    case Accent::Acute:
      return kAcute;
    case Accent::Grave:
      return kGrave;
    case Accent::Circumflex:
      return kCircumflex;
    case Accent::Tilde:
      return kTilde;
    case Accent::Diaeresis:
      return kDiaeresis;
    case Accent::Ring:
      return kRing;
    case Accent::Cedilla:
      return kCedilla;
    case Accent::None:
      break;
  }
  return nullptr;
}

Glyph glyph_for(const std::uint32_t code) {
  if (code >= 0x20 && code <= 0x7E) {
    return ascii(static_cast<char>(code));
  }
  // Latin-1 letters: base letter + accent. Upper and lower case share the pattern 0x20 apart.
  struct Composed {
    std::uint32_t code;
    char base;
    Accent accent;
  };
  static constexpr Composed kComposed[] = {
      {0xC0, 'A', Accent::Grave},      {0xC1, 'A', Accent::Acute},     {0xC2, 'A', Accent::Circumflex},
      {0xC3, 'A', Accent::Tilde},      {0xC4, 'A', Accent::Diaeresis}, {0xC5, 'A', Accent::Ring},
      {0xC7, 'C', Accent::Cedilla},    {0xC8, 'E', Accent::Grave},     {0xC9, 'E', Accent::Acute},
      {0xCA, 'E', Accent::Circumflex}, {0xCB, 'E', Accent::Diaeresis}, {0xCC, 'I', Accent::Grave},
      {0xCD, 'I', Accent::Acute},      {0xCE, 'I', Accent::Circumflex}, {0xCF, 'I', Accent::Diaeresis},
      {0xD1, 'N', Accent::Tilde},      {0xD2, 'O', Accent::Grave},     {0xD3, 'O', Accent::Acute},
      {0xD4, 'O', Accent::Circumflex}, {0xD5, 'O', Accent::Tilde},     {0xD6, 'O', Accent::Diaeresis},
      {0xD9, 'U', Accent::Grave},      {0xDA, 'U', Accent::Acute},     {0xDB, 'U', Accent::Circumflex},
      {0xDC, 'U', Accent::Diaeresis},  {0xDD, 'Y', Accent::Acute},
  };
  for (const Composed& entry : kComposed) {
    if (code == entry.code) {
      return accented(entry.base, entry.accent);
    }
    if (code == entry.code + 0x20) {
      return accented(static_cast<char>(entry.base - 'A' + 'a'), entry.accent);
    }
  }
  switch (code) {
    case 0xFF:
      return accented('y', Accent::Diaeresis);
    case 0xB7:
      return Glyph{kMiddleDot};
    case 0x2022:
      return Glyph{kBullet};
    case 0xB0:
    case 0xBA:
      return Glyph{kDegree};
    case 0xAA:
      return ascii('a');
    case 0xD7:
      return ascii('x');
    case 0xF7:
      return ascii('/');
    case 0xDF:
      return ascii('B');
    case 0xAB:
    case 0x2039:
    case 0x2190:
      return ascii('<');
    case 0xBB:
    case 0x203A:
    case 0x2192:
      return ascii('>');
    case 0x2191:
      return ascii('^');
    case 0x2193:
      return ascii('v');
    case 0xBF:
      return ascii('?');
    case 0xA1:
      return ascii('!');
    case 0x2013:
    case 0x2014:
    case 0x2212:
      return ascii('-');
    case 0x2018:
    case 0x2019:
      return ascii('\'');
    case 0x201C:
    case 0x201D:
      return ascii('"');
    case 0x20AC:
      return ascii('E');
    case 0xA0:
      return ascii(' ');
    default:
      return Glyph{kBox};
  }
}

