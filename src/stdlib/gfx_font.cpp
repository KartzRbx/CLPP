[[nodiscard]] Glyph ascii(const char c) {
  const auto index = static_cast<unsigned char>(c) - 0x20U;
  return Glyph{kAscii[index], Accent::None, false, false};
}

[[nodiscard]] Glyph accented(const char base, const Accent accent) {
  Glyph glyph = ascii(base);
  glyph.accent = accent;
  glyph.lowercase = base >= 'a' && base <= 'z';
  glyph.dotless = base == 'i';
  return glyph;
}

