// Structural editor grammar. The compiler LSP remains the semantic authority.
const comma = rule => optional(seq(rule, repeat(seq(',', rule)), optional(',')));
module.exports = grammar({
  name: 'clpp', extras: $ => [/[ \t\r\n\v\f]/, $.comment], word: $ => $.identifier,
  externals: $ => [$.comment],
  reserved: { global: $ => ['true', 'false', 'null'] },
  conflicts: $ => [[$._type, $._expression], [$.type_identifier, $._expression],
    [$.initializer_list, $.block], [$._expression, $.field_initializer], [$.qualified_type, $._expression],
    [$.generic_call_expression, $.generic_function_expression, $._expression],
    [$.generic_call_expression, $.generic_function_expression],
    [$.type_identifier, $._expression, $.generic_call_expression, $.generic_function_expression], [$.template_clause, $.modifier]],
  rules: {
    source_file: $ => repeat($._statement),
    _statement: $ => choice($.definition, $.enum_definition, $.function_definition,
      $.variable_declaration, $.atomic_declaration, $.expression_statement, $.if_statement,
      $.while_statement, $.do_statement, $.for_statement, $.guard_statement, $.try_statement,
      $.return_statement, $.jump_statement, $.link_statement, $.pragma_statement, $.match_statement, $.switch_statement, ';'),
    modifier: $ => choice('export', 'abstract', 'final', 'override',
      'public', 'private', 'async', 'const', 'constexpr', 'observable', 'extern'),
    definition: $ => seq(repeat($.modifier), 'def', field('name', $.type_identifier),
      optional($.type_parameters), choice(seq('=', $._type, ';'),
        seq(optional(seq(':', comma($._type))), $.definition_body))),
    definition_body: $ => seq('{', repeat(choice($.function_definition, $.variable_declaration,
      $.definition, $.enum_definition, ';')), '}'),
    enum_definition: $ => seq(optional('export'), 'enum', 'class',
      field('name', $.type_identifier), '{', comma($.enum_member), '}'),
    enum_member: $ => field('name', $.identifier),
    template_clause: $ => seq(optional('export'), 'template', '<', comma(seq('typename', $.type_identifier,
      optional(seq(':', $._type)))), '>'),
    type_parameters: $ => seq('<', comma($.type_identifier), '>'),
    type_arguments: $ => seq('<', comma($._type), '>'),
    _type: $ => choice($.builtin_type, $.type_identifier, $.qualified_type, $.generic_type,
      $.function_type, $.union_type, $.intersection_type, $.string),
    type_identifier: $ => alias($.identifier, $.type_identifier),
    qualified_type: $ => seq(field('module', $.identifier), '.', field('name', $.type_identifier)),
    generic_type: $ => prec(3, seq(field('name', choice($.type_identifier, $.builtin_type,
      $.qualified_type)), $.type_arguments)),
    function_type: $ => prec.right(seq('(', comma($._type), ')', '->', $._type)),
    union_type: $ => prec.left(1, seq($._type, '|', $._type)),
    intersection_type: $ => prec.left(2, seq($._type, '&', $._type)),
    function_definition: $ => seq(optional($.template_clause), repeat($.modifier),
      field('return_type', $._type), field('name', choice($.identifier, $.qualified_function_name, $.operator_name)),
      $.parameters, optional($.where_clause), choice(field('body', $.block), ';')),
    qualified_function_name: $ => seq(field('owner', $.type_identifier), '::', field('name', $.identifier)),
    operator_name: $ => seq('operator', choice('+', '-', seq('[', ']'))),
    parameters: $ => seq('(', comma(alias($.typed_parameter, $.parameter)), ')'),
    typed_parameter: $ => seq(field('type', $._type), optional('...'), field('name', $.identifier)),
    lambda_parameters: $ => seq('(', comma($.parameter), ')'),
    parameter: $ => seq(optional(field('type', $._type)), field('name', $.identifier)),
    where_clause: $ => seq('where', comma(seq($.type_identifier, ':', $._type))),
    variable_declaration: $ => seq(repeat($.modifier),
      field('type', choice($._type, 'auto', $.decltype_type)), field('name', $.identifier), optional(seq('=', $._expression)), ';'),
    decltype_type: $ => seq('decltype', '(', $._expression, ')'),
    atomic_declaration: $ => seq('atomic', field('name', $.identifier), '=', $._expression, ';'),
    block: $ => seq('{', repeat($._statement), '}'),
    expression_statement: $ => seq($._expression, ';'),
    if_statement: $ => prec.right(seq('if', $.condition, $.block, optional(seq('else', choice($.block, $.if_statement))))),
    condition: $ => seq('(', $._expression, ')'),
    while_statement: $ => seq('while', $.condition, $.block),
    do_statement: $ => seq('do', $.block, 'while', $.condition, ';'),
    for_statement: $ => seq('for', '(', choice(
      seq(field('type', choice($._type, 'auto')), field('name', $.identifier), 'in', $._expression),
      seq(choice($.variable_declaration, seq(optional($._expression), ';')),
        optional($._expression), ';', optional($._expression))), ')', $.block),
    guard_statement: $ => seq('guard', $.condition, 'else', $.block),
    match_statement: $ => seq('match', $.condition, '{', repeat($.match_arm), '}'),
    match_arm: $ => seq($._expression, optional(seq('guard', $._expression)), '=>', choice($.block, $._statement)),
    switch_statement: $ => seq('switch', $.condition, '{', repeat($.switch_arm), '}'),
    switch_arm: $ => seq(choice(seq('case', $._expression), 'default'), ':', repeat($._statement)),
    try_statement: $ => seq('try', $.block, 'catch', optional(seq('(', $.identifier, ')')), $.block),
    return_statement: $ => seq('return', optional($._expression), ';'),
    jump_statement: $ => seq(choice('break', 'continue'), ';'),
    link_statement: $ => seq('link', choice($.string,
      seq($.special_identifier, repeat(seq('.', $.identifier)))), optional(seq('as', $.identifier)), ';'),
    pragma_statement: $ => seq('pragma', choice('strict', 'nostrict'), ';'),
    _expression: $ => choice($.identifier, $.builtin_function, $.builtin_type, $.special_identifier,
      $.string, $.template_string, $.number, $.boolean, $.null, $.parenthesized_expression, $.call_expression, $.generic_call_expression, $.generic_function_expression,
      $.member_expression, $.subscript_expression, $.binary_expression, $.unary_expression,
      $.assignment_expression, $.conditional_expression, $.lambda_expression,
      $.initializer_list, $.object_expression, $.update_expression, $.cast_expression, $.typed_expression),
    cast_expression: $ => prec(20, seq('static_cast', '<', field('type', $._type), '>', '(', $._expression, ')')),
    typed_expression: $ => seq('(', field('type', $._type), field('value', $._expression), ')'),
    parenthesized_expression: $ => prec.dynamic(1, seq('(', $._expression, ')')),
    call_expression: $ => prec(18, seq(field('function', $._expression), $.arguments)),
    generic_call_expression: $ => prec.dynamic(1, seq(field('function', choice($.identifier, $.member_expression, $.builtin_type)), $.type_arguments, $.arguments)),
    generic_function_expression: $ => prec.dynamic(1, seq(field('function', choice($.identifier, $.member_expression)), $.type_arguments)),
    arguments: $ => seq('(', comma($._expression), ')'),
    member_expression: $ => prec.left(19, seq(field('object', $._expression),
      choice('.', '::', '~>'), field('property', $.identifier))),
    subscript_expression: $ => prec(19, seq($._expression, '[', $._expression, ']')),
    initializer_list: $ => seq('{', comma($._expression), '}'),
    object_expression: $ => prec(18, seq(field('type', $._type), '{', comma($.field_initializer), '}')),
    field_initializer: $ => seq(field('name', $.identifier), '=', $._expression),
    lambda_expression: $ => seq(optional('async'), 'func', $.lambda_parameters, '->', $._type, $.block),
    assignment_expression: $ => prec.right(1, seq(field('left', $._expression),
      choice('=', '+=', '-=', '*=', '/=', '%='), field('right', $._expression))),
    conditional_expression: $ => prec.right(2, seq($._expression, '?', $._expression, ':', $._expression)),
    binary_expression: $ => choice(...[
      [3, ['||', 'or']], [4, ['&&', 'and']], [5, ['|']], [6, ['^']], [7, ['&']],
      [8, ['==', '!=']], [9, ['<', '>', '<=', '>=']], [10, ['shl', 'shr', '..']],
      [11, ['+', '-', '.:']], [12, ['*', '/', '%']],
    ].map(([priority, operators]) => prec.left(priority,
      seq($._expression, field('operator', operators.length === 1 ? operators[0] : choice(...operators)), $._expression)))),
    unary_expression: $ => prec(15, seq(choice('!', 'not', '-', '~', 'await', 'spawn', 'thread', 'move'), $._expression)),
    update_expression: $ => prec.left(16, choice(seq($._expression, choice('++', '--')), seq(choice('++', '--'), $._expression))),
    builtin_function: $ => choice('post', 'warn', 'report', 'parallel', 'join'),
    builtin_type: $ => choice('number', 'float', 'bool', 'string', 'void', 'any',
      'array', 'dictionary', 'optional', 'tuple', 'task', 'signal', 'connection', 'buffer', 'Vector2', 'Vector3', 'Vector4'),
    boolean: $ => choice('true', 'false'), null: $ => 'null',
    string: $ => choice(seq('"', repeat(choice($.string_content, $.escape_sequence)), '"'),
      seq("'", repeat(choice($.single_string_content, $.escape_sequence)), "'")),
    single_string_content: $ => token.immediate(/[^'\\\r\n]+/),
    string_content: $ => token.immediate(/[^"\\\r\n]+/), escape_sequence: $ => token.immediate(/\\./),
    template_string: $ => seq('`', repeat(choice($.template_content, $.escape_sequence, $.interpolation)), '`'),
    template_content: $ => token.immediate(/[^`\\$]+|\$[^{]/),
    interpolation: $ => seq('${', $._expression, '}'),
    number: $ => token(choice(/0[xX][0-9a-fA-F_]+/, /0[bB][01_]+/,
      /[0-9][0-9_]*(\.[0-9_]+)?([eE][+-]?[0-9_]+)?/)),
    special_identifier: $ => token(seq('@', /[a-zA-Z_][a-zA-Z0-9_]*/)),
    identifier: $ => /[a-zA-Z_\u0080-\u{10ffff}][a-zA-Z0-9_\u0080-\u{10ffff}]*/u,
  }
});
